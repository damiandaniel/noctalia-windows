"""Make a compile-only meson.build from upstream Noctalia, minus the Linux-only folders."""

import argparse
import re
import sys
from pathlib import Path

# Folders (and files) that only make sense on Linux. Keep in sync with docs/upstream-seams.md.
DROP = (
    "src/dbus/",
    "src/wayland/",
    "src/compositors/",
    "src/pipewire/",
    "src/capture/",
    "src/idle/",
    "src/security/",
    "src/auth/",
    "src/shell/lockscreen/",
)

# pkg-config names. All optional: a missing one is reported, not fatal.
DEPS = [
    "freetype2", "fontconfig", "cairo", "cairo-ft", "pango", "pangocairo", "pangoft2",
    "harfbuzz", "librsvg-2.0", "xkbcommon", "glib-2.0", "gobject-2.0", "gio-2.0",
    "libsodium", "libcurl", "libqalculate", "nlohmann_json", "libxml-2.0", "libical",
    "tomlplusplus", "md4c", "libwebp", "libwebpdemux", "libjxl", "libjxl_threads",
    "sndfile", "egl", "glesv2",
]

LUAU_INC = ["Common", "Ast", "Bytecode", "Compiler", "VM"]


def read_sources(meson_text):
    m = re.search(r"^_noctalia_sources\s*=\s*files\(\n(.*?)^\)", meson_text, re.S | re.M)
    if not m:
        sys.exit("Could not find _noctalia_sources in upstream meson.build")
    return re.findall(r"'(src/[^']+\.(?:cpp|cc|c))'", m.group(1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--upstream", default="third_party/noctalia")
    ap.add_argument("--out", default="meson.build")
    args = ap.parse_args()

    up = Path(args.upstream)
    sources = read_sources((up / "meson.build").read_text(encoding="utf-8"))
    kept = [s for s in sources if not s.startswith(DROP)]
    dropped = len(sources) - len(kept)
    missing = [s for s in kept if not (up / s).exists()]
    if missing:
        sys.exit(f"Listed in upstream meson.build but not on disk: {missing[:3]}")

    prefix = args.upstream.rstrip("/")
    src_lines = "\n".join(f"  '{prefix}/{s}'," for s in kept)
    dep_lines = "\n".join(f"  '{d}'," for d in DEPS)
    luau = "\n".join(f"  '{prefix}/third_party/luau/{d}/include'," for d in LUAU_INC)

    text = f"""# Generated by scripts/gen-stripped-meson.py. Do not edit.
# Compile-only check of upstream Noctalia without the Linux-only folders.
project('noctalia-windows-stripped', ['c', 'cpp'],
  version: files('{prefix}/VERSION'),
  meson_version: '>=1.1',
  default_options: ['cpp_std=c++23', 'cpp_extensions=false', 'warning_level=0'],
)

dep_names = [
{dep_lines}
]
deps = []
foreach name : dep_names
  d = dependency(name, required: false)
  if d.found()
    deps += d
  else
    message('missing dependency: ' + name)
  endif
endforeach

cfg = configuration_data()
cfg.set('VCS_TAG', 'windows-stripped')
configure_file(
  input: '{prefix}/src/core/git_revision.h.in',
  output: 'noctalia_git_revision.h',
  configuration: cfg,
)

inc = include_directories(
  '{prefix}/src',
  '{prefix}/third_party/wuffs',
  '{prefix}/third_party/fzy/src',
  '{prefix}/third_party/material_color_utilities',
{luau}
  '.',
  is_system: false,
)

sources = files(
{src_lines}
)

static_library('noctalia_stripped',
  sources,
  dependencies: deps,
  include_directories: inc,
  cpp_args: [
    '-w',
    '-DNOCTALIA_INSTALL_PREFIX="C:/noctalia"',
    '-DNOCTALIA_INSTALL_DATADIR="share"',
    '-DNOCTALIA_VERSION="' + meson.project_version().strip() + '"',
  ],
)
"""
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"upstream sources : {len(sources)}")
    print(f"dropped (Linux)  : {dropped}")
    print(f"kept             : {len(kept)}")
    print(f"wrote            : {args.out}")


if __name__ == "__main__":
    main()
